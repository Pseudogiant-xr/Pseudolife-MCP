"""Validate the Rust daemon's native schema inputs and derive only schema_meta.rs."""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

STORAGE = Path(__file__).resolve().parents[1] / "src" / "storage"
PLAN_SHA256 = "541ace8f10c8df08cfaf89c1c6814bf1b02b811e59059861e624099d949f4124"


def load_schema_plan(storage: Path = STORAGE) -> dict:
    return json.loads((storage / "schema_plan.json").read_text(encoding="utf-8"))


def plan_fingerprint(plan: dict, ddl: str) -> str:
    payload = json.dumps((plan, ddl), sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def render_metadata(storage: Path) -> bytes:
    plan = load_schema_plan(storage)
    version = plan["schema_version"]
    dimension = plan["embedding_dimension"]
    if type(version) is not int or not 1 <= version < 2**63:
        raise ValueError("schema_plan.json schema_version must be a positive i64 integer")
    if type(dimension) is not int or not 1 <= dimension < 2**31:
        raise ValueError("schema_plan.json embedding_dimension must be a positive i32 integer")
    ddl = (storage / "schema.sql").read_text(encoding="utf-8")
    header, _, body = ddl.partition("\n")
    if header != f"-- schema_version {version}":
        raise ValueError(f"schema.sql header must be '-- schema_version {version}'")

    dimensions = set(re.findall(
        r"^\s*embedding\s+vector\s*\(\s*(\d+)\s*\)", body, re.I | re.M,
    ))
    if dimensions != {str(dimension)}:
        raise ValueError(
            f"schema.sql embedding dimensions {sorted(dimensions)} must match "
            f"schema_plan.json embedding_dimension {dimension}"
        )

    refusal = plan["embedding_refusal"]
    refusal_dimensions = set(re.findall(r"\bvector\((\d+)\)", refusal))
    refusal_dimensions.update(re.findall(r"\b(\d+)-d\b", refusal))
    if refusal_dimensions != {str(dimension)}:
        raise ValueError(f"schema_plan.json embedding_refusal must name embedding_dimension {dimension}")

    stamp = plan["steps"][-1]
    if (
        stamp["op"] != "sql"
        or "VALUES ('schema_version', $1::jsonb)" not in stamp["sql"]
        or stamp["parameters"] != [str(version)]
    ):
        raise ValueError(f"schema_plan.json must end by stamping schema_version {version}")

    return (
        "// Generated by harness/gen_schema_sql.py; do not edit.\n"
        f"pub const SCHEMA_META_VERSION: i64 = {version};\n"
        f"pub const EXPECTED_EMBEDDING_DIM: i32 = {dimension};\n"
    ).encode("utf-8")


def main(argv: list[str] | None = None, *, storage: Path = STORAGE) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="check schema_meta.rs against the native inputs without writing it")
    args = parser.parse_args(argv)

    try:
        expected = render_metadata(storage)
        metadata = storage / "schema_meta.rs"
        if args.check:
            if not metadata.exists() or metadata.read_bytes() != expected:
                raise ValueError(
                    "stale schema_meta.rs; run python rust/daemon/harness/gen_schema_sql.py"
                )
            print("native schema inputs and generated schema_meta.rs agree")
        else:
            metadata.write_bytes(expected)
            print("generated schema_meta.rs")
    except (OSError, ValueError, KeyError, IndexError, TypeError) as exc:
        print(f"schema check: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
