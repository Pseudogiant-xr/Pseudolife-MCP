"""Generate the Unicode 14 table behind the Rust port of ``repr(str)``.

CPython 3.11's ``repr()`` of a ``str`` escapes every code point that
``str.isprintable()`` rejects (``Py_UNICODE_ISPRINTABLE``: general category
Cc, Cf, Cs, Co, Cn, Zl, Zp, or Zs other than the space). The Rust port
(``crate::storage::py_printable``) reads that set from this table, so its
behavior rests on CPython's Unicode 14 data, not on the host compiler's.

The digest covers ``isprintable`` over every code point, so the Rust unit
test recomputes it from the committed ranges.

usage: python gen_py_repr_unicode.py [--check]
"""
import argparse
import hashlib
import sys
import unicodedata
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / "src" / "py_repr_unicode14.rs"


def ranges(pred):
    out, start = [], None
    for c in range(0x110000):
        if pred(c):
            if start is None:
                start = c
        elif start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def digest(pred) -> str:
    return hashlib.sha256(bytes(1 if pred(c) else 0 for c in range(0x110000))).hexdigest()


def render() -> str:
    if sys.version_info[:2] != (3, 11) or unicodedata.unidata_version != "14.0.0":
        raise SystemExit("run with CPython 3.11 (Unicode 14.0.0)")

    def nonprintable(c):
        return not chr(c).isprintable()

    lines = [
        "//! Generated by harness/gen_py_repr_unicode.py with CPython 3.11, Unicode 14.0.0.",
        "//! `str.isprintable()` behind `repr(str)`; do not edit by hand.",
        "",
        "#[cfg(test)]",
        f'pub const NONPRINTABLE_SHA256: &str = "{digest(nonprintable)}";',
        "",
        "/// The code points `str.isprintable()` rejects, as inclusive ranges.",
        "pub const NONPRINTABLE: &[(u32, u32)] = &[",
    ]
    lines += [f"    (0x{a:x}, 0x{b:x})," for a, b in ranges(nonprintable)]
    lines += ["];", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    text = render()
    if ap.parse_args().check:
        if TARGET.read_text(encoding="utf-8") != text:
            print(f"{TARGET} is stale", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
