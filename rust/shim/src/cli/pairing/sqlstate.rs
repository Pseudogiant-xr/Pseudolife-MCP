/// `type(exc).__name__` of the psycopg error a server error raises.
pub(super) fn class_name(code: &str) -> &'static str {
    let code = code.to_ascii_uppercase();
    if let Ok(index) = BY_CODE.binary_search_by(|(c, _)| (*c).cmp(code.as_str())) {
        return BY_CODE[index].1;
    }
    for prefix in [code.get(..2), code.get(..1)].into_iter().flatten() {
        if let Some((_, class)) = BY_CLASS.iter().find(|(c, _)| *c == prefix) {
            return class;
        }
    }
    "DatabaseError"
}

#[cfg(test)]
mod tests {
    #[test]
    fn classes_follow_psycopg() {
        assert_eq!(super::class_name("42P01"), "UndefinedTable");
        assert_eq!(super::class_name("57014"), "QueryCanceled");
        assert_eq!(super::class_name("08ZZZ"), "OperationalError");
        assert_eq!(super::class_name("ZZ000"), "DatabaseError");
    }
}
